def main() -> int:
    payload = json.loads(REFINED_PATH.read_text(encoding="utf-8"))
    text = payload["refined_text"]
    marker = "ฉากเช่นนี้ไม่ได้เกิดขึ้น"
    cut = text.find(marker)
    if cut < 0:
        raise RuntimeError("cut marker not found")
    repaired = text[:cut].rstrip() + "\n\n" + TAIL
    metadata = payload.setdefault("metadata", {})
    metadata["manual_repair"] = "appended_missing_office_scene_after_qa_hard_fail"
    metadata["manual_repair_reason"] = "provider refinement omitted source tail from trending transition through chapter ending"
    payload["refined_text"] = repaired
    REFINED_PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"repaired refined text: {len(text)} -> {len(repaired)} chars")
    for needle in ["หัวหน้าแผนก", "ไคล์", "โรวัน", "เซเรลิธ", "แคเลน", "ซาราห์"]:
        print(f"{needle}: {needle in repaired}")
    return 0


